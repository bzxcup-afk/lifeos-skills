// 从文本中提取药物名称
export function extractDrugName(text: string): string | null {
  const lower = text.toLowerCase();
  
  for (const keyword of DRUG_KEYWORDS) {
    if (lower.includes(keyword.toLowerCase())) {
      return keyword;
    }
  }
  
  return null;
}

