// 获取药物提示（最多3条）
export function getDrugTips(drugName: string): string[] {
  const category = getDrugCategory(drugName);
  const tips = DRUG_TIPS[category] || DRUG_TIPS[' default'];
  
  // 返回最多3条
  return tips.slice(0, 3);
}

// 检测是否提到了"药"
export function hasDrugMention(text: string): boolean {
  const lower = text.toLowerCase();
  return DRUG_KEYWORDS.some(k => lower.includes(k.toLowerCase()));
}
